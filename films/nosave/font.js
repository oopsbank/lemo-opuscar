// —— Vietnamese: every accented letter is composed from its base glyph plus pixel marks (NFD), stacked above or placed below ——
// The line box: 5 rows for marks above the caps, 7 cap rows, 2 descender rows, 1 for the dot below → 15.
export const TOP = 5, LINE_H = 16;
const MARK = {
  '́': ['.#', '#.'],          // acute (sắc)
  '̀': ['#.', '.#'],          // grave (huyền)
  '̉': ['##', '.#', '#.'],    // hook above (hỏi)
  '̃': ['.#.#', '#.#.'],      // tilde (ngã)
  '̂': ['.#.', '#.#'],        // circumflex (â ê ô)
  '̆': ['#.#', '.#.'],        // breve (ă)
};
const HORN = '̛', DOTB = '̣';
G['đ'] = ['...#', '..###', '.###', '#..#', '#..#', '#..#', '.###'].map(r => r.padEnd(5, '.'));
G['Đ'] = ['.####.', '.#...#', '.#...#', '####.#', '.#...#', '.#...#', '.####.'];
G['ı'] = ['.', '.', '#', '#', '#', '#', '#'];
const clusters = s => { const out = []; for (const ch of s.normalize('NFD')) { if (/[̀-ͯ]/.test(ch) && out.length) out[out.length - 1].m.push(ch); else out.push({ b: ch, m: [] }); } return out; };
export const glyphW = ch => (G[ch] || G['?'])[0].length;
const clW = c => glyphW(c.b === 'i' && c.m.some(m => MARK[m]) ? 'ı' : c.b) + (c.m.includes(HORN) ? 1 : 0);
export function textW(s) { let w = 0; for (const c of clusters(s)) w += clW(c) + 1; return Math.max(0, w - 1); }
export const charCount = s => clusters(s).length;
// draw: y0 is the top of the line box; returns the right edge. n = how many clusters to show (typing)
export function text(fb, s, x0, y0, col, shadow = null, n = Infinity) {
  let x = x0, k = 0;
  for (const c of clusters(s)) {
    if (k++ >= n) break;
    const up = c.b === c.b.toUpperCase() && c.b !== c.b.toLowerCase(), base = c.b === 'i' && c.m.some(m => MARK[m]) ? 'ı' : c.b, g = G[base] || G['?'], gw = g[0].length;
    const put = (X, Y, ink) => { if (shadow !== null) fb.px(X + 1, Y + 1, shadow); fb.px(X, Y, ink); };
    const pts = [];
    for (let y = 0; y < g.length; y++) for (let b = 0; b < g[y].length; b++) if (g[y][b] === '#') pts.push([x + b, y0 + TOP + y]);
    // marks: the first above sits just over the letter's top (caps row 0, lowercase x-height row 2); a second one stacks above it
    let top = up || 'bdfhklt'.includes(c.b) ? -1 : 1, mw = 0;
    const above = c.m.filter(m => MARK[m]); above.sort((a, b) => ('̂̆'.includes(b) ? 1 : 0) - ('̂̆'.includes(a) ? 1 : 0));
    for (const m of above) { const r = MARK[m], mx = x + Math.floor((gw - r[0].length) / 2) + (m === '́' && above.length > 1 ? 1 : 0); for (let y = 0; y < r.length; y++) for (let b = 0; b < r[y].length; b++) if (r[y][b] === '#') pts.push([mx + b, y0 + TOP + top - r.length + 1 + y]); top -= r.length + (up ? 0 : 0); }
    if (c.m.includes(HORN)) { pts.push([x + gw, y0 + TOP + (up ? 0 : 2)]); pts.push([x + gw, y0 + TOP + (up ? 1 : 3)]); mw = 1; }
    if (c.m.includes(DOTB)) pts.push([x + Math.floor(gw / 2), y0 + TOP + 8]);
    if (shadow !== null) for (const [X, Y] of pts) fb.px(X + 1, Y + 1, shadow);
    for (const [X, Y] of pts) fb.px(X, Y, typeof col === 'function' ? col(Y - y0) : col);
    x += gw + mw + 1;
  }
  return x;
}
// word wrap by pixel width
export function wrap(s, maxW) { const words = s.split(' '), lines = []; let cur = ''; for (const w of words) { const t = cur ? cur + ' ' + w : w; if (textW(t) > maxW && cur) { lines.push(cur); cur = w; } else cur = t; } if (cur) lines.push(cur); return lines; }
